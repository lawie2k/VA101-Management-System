export default function AdminLeftSidebar({ role }: { role: string }) {
  const pathname = usePathname();

  // Filter links based on role
  const getVisibleLinks = () => {
    switch (role) {
      case "finance":
        return ALL_LINKS.filter((l) =>
          ["Dashboard", "Contracts", "Assignments", "Settings"].includes(l.label)
        );
      case "employee":
        return ALL_LINKS.filter((l) =>
          [
            "Dashboard",
            "Job Approvals",
            "Manage Jobs",
            "VA Applications",
            "Initial Interviews",
            "Client Interviews",
            "Shortlists",
            "Training Materials",
            "Discovery Calls",
            "Settings",
          ].includes(l.label)
        );
      case "admin":
      default: // Super Admin gets everything
        return ALL_LINKS;
    }
  };

  const links = getVisibleLinks();

  const roleLabel =
    role === "admin"
      ? "SUPER ADMIN"
      : role === "finance"
      ? "FINANCE ADMIN"
      : role === "employee"
      ? "OPERATIONS ADMIN"
      : "ADMIN";

  return (
    <aside className="fixed left-0 top-0 h-screen w-64 bg-[#0a0f1c] text-slate-300 border-r border-[#1C1C1E] flex flex-col z-50">
      {/* Brand & Role Header */}
      <div className="p-6">
        <Link href="/admin/dashboard" className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-lg bg-emerald-500 flex items-center justify-center text-white font-black text-xs">
            VA
          </div>
          <span className="text-white font-bold tracking-wider">VA101</span>
        </Link>
        <p className="mt-8 text-[10px] font-black text-slate-500 uppercase tracking-widest px-2">
          {roleLabel}
        </p>
      </div>

      {/* Navigation Links */}
      <nav className="flex-1 overflow-y-auto scrollbar-none px-4 space-y-1 pb-6">
        {links.map((link) => {
          const isActive = pathname.startsWith(link.href);
          return (
            <Link
              key={link.href}
              href={link.href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold transition-all ${
                isActive
                  ? "bg-blue-600/10 text-blue-500"
                  : "hover:bg-slate-800/50 hover:text-white"
              }`}
            >
              <span className={`text-base ${isActive ? "opacity-100" : "opacity-60"}`}>
                {link.icon}
              </span>
              {link.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
