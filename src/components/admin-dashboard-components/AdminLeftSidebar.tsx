export default function AdminLeftSidebar({ role, isOpen, setIsOpen }: { role: string; isOpen?: boolean; setIsOpen?: (v: boolean) => void }) {
  const pathname = usePathname();

  // Filter links based on role
  const getVisibleLinks = () => {
    switch (role) {
      case "finance":
        return ALL_LINKS.filter((l) =>
          ["Dashboard", "Client Invoices", "VA Course Purchases", "Student Course Purchases", "Staff Payouts", "Commissions", "Audit Ledger", "Reports"].includes(l.label)
        );
      case "employee":
        return ALL_LINKS.filter((l) =>
          [
            "Dashboard",
            "Job Approvals",
            "Course Approvals",
            "Manage Jobs",
            "Manage Courses",
            "VA Applications",
            "Initial Interviews",
            "Client Interviews",
            "Shortlists",
            "Discovery Calls",
          ].includes(l.label)
        );
      case "admin":
      default: // Super Admin gets everything EXCEPT finance
        return ALL_LINKS.filter((l) =>
          !["Client Invoices", "VA Course Purchases", "Student Course Purchases", "Staff Payouts", "Commissions", "Audit Ledger", "Reports"].includes(l.label)
        );
    }
  };

  const links = getVisibleLinks();

  const roleLabel =
    role === "admin"
      ? "SUPER ADMIN"
      : role === "finance"
      ? "FINANCE ADMIN"
      : role === "employee"
      ? "OPERATIONS ADMIN"
      : "ADMIN";

  return (
    <>
      {/* Mobile Backdrop */}
      {isOpen && (
        <div 
          className="fixed inset-0 bg-slate-900/50 z-40 lg:hidden"
          onClick={() => setIsOpen?.(false)}
        />
      )}
      <aside className={`fixed left-0 top-0 h-screen w-64 bg-[#0a0f1c] text-slate-300 border-r border-[#1C1C1E] flex flex-col z-50 transform transition-transform duration-300 ease-in-out ${isOpen ? "translate-x-0" : "-translate-x-full lg:translate-x-0"}`}>
      {/* Brand & Role Header */}
      <div className="p-6">
        <Link href="/admin/dashboard" className="flex items-center gap-3">
          <img 
            src="/logo/VA101%20logo1.svg" 
            alt="VA 101 Logo" 
            className="h-16 w-auto object-contain"
          />
        </Link>
        <p className="mt-8 text-[10px] font-black text-slate-500 uppercase tracking-widest px-2">
          {roleLabel}
        </p>
      </div>

      {/* Navigation Links */}
      <nav className="flex-1 overflow-y-auto scrollbar-none px-4 space-y-1 pb-6">
        {links.map((link) => {
          const isActive = pathname.startsWith(link.href);
          return (
            <Link
              key={link.href}
              href={link.href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold transition-all ${
                isActive
                  ? "bg-blue-600/10 text-blue-500"
                  : "hover:bg-slate-800/50 hover:text-white"
              }`}
              onClick={() => setIsOpen?.(false)}
            >
              <span className={`text-base ${isActive ? "opacity-100" : "opacity-60"}`}>
                {link.icon}
              </span>
              {link.label}
            </Link>
          );
        })}
      </nav>
      
      {/* Pinned Settings Link */}
      <div className="p-4 border-t border-[#1C1C1E]">
        <Link
          href="/admin/settings"
          className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold transition-all ${
            pathname.startsWith("/admin/settings")
              ? "bg-blue-600/10 text-blue-500"
              : "hover:bg-slate-800/50 hover:text-white"
          }`}
          onClick={() => setIsOpen?.(false)}
        >
          <span className={`text-base ${pathname.startsWith("/admin/settings") ? "opacity-100" : "opacity-60"}`}>
            <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M10.325 4.317c.426-1.756 2.924-1.756 3.35 0a1.724 1.724 0 002.573 1.066c1.543-.94 3.31.826 2.37 2.37a1.724 1.724 0 001.065 2.572c1.756.426 1.756 2.924 0 3.35a1.724 1.724 0 00-1.066 2.573c.94 1.543-.826 3.31-2.37 2.37a1.724 1.724 0 00-2.572 1.065c-.426 1.756-2.924 1.756-3.35 0a1.724 1.724 0 00-2.573-1.066c-1.543.94-3.31-.826-2.37-2.37a1.724 1.724 0 00-1.065-2.572c-1.756-.426-1.756-2.924 0-3.35a1.724 1.724 0 001.066-2.573c-.94-1.543.826-3.31 2.37-2.37.996.608 2.296.07 2.572-1.065z"></path><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M15 12a3 3 0 11-6 0 3 3 0 016 0z"></path></svg>
          </span>
          Settings
        </Link>
      </div>
    </aside>
    </>
  );
}
